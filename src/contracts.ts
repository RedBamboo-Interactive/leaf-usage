const SNAPSHOT_KEYS = ["schemaVersion", "snapshotId", "storyId", "storyVersion", "period", "rows"] as const

/** Story-independent checks: strict keys, ids, a real calendar date and a rows array. */
export function validateSnapshotEnvelope(input: unknown): Result<SnapshotEnvelope> {
  if (!object(input) || !only(input, SNAPSHOT_KEYS)) return fail("The snapshot contains unsupported fields.")
  if (!has(input, SNAPSHOT_KEYS)) return fail("The snapshot is missing required fields.")
  if (input.schemaVersion !== 1) return fail("Unsupported snapshot schema version.")
  if (typeof input.snapshotId !== "string" || !SNAPSHOT_ID.test(input.snapshotId)) return fail("snapshotId must be a lowercase UUID.")
  if (!isStoryId(input.storyId)) return fail("Invalid storyId.")
  if (!integer(input.storyVersion, 1, MAX_STORY_VERSION)) return fail("storyVersion must be a positive integer.")
  if (parseUtcDay(input.period) === null) return fail("period must be a real UTC date (YYYY-MM-DD).")
  if (!Array.isArray(input.rows) || input.rows.length > MAX_ROWS) return fail(`rows must be an array of at most ${MAX_ROWS} entries.`)
  return {
    ok: true,
    value: {
      schemaVersion: 1,
      snapshotId: input.snapshotId,
      storyId: input.storyId,
      storyVersion: input.storyVersion,
      period: input.period as string,
      rows: input.rows,
    },
  }
}

/**
 * Validates a snapshot against the stored story definition. Returns the rows in canonical form
 * (dimension and measure keys in definition order, rows sorted by dimension values) so an identical
 * retry produces identical bytes.
 */
export function validateSnapshot(input: unknown, story: StoryDefinition, now: Date): Result<Snapshot> {
  const envelope = validateSnapshotEnvelope(input)
  if (!envelope.ok) return envelope
  const snapshot = envelope.value
  if (snapshot.storyId !== story.storyId || snapshot.storyVersion !== story.version) {
    return fail("The snapshot does not belong to this story version.")
  }

  const period = parseUtcDay(snapshot.period)!
  const today = utcDay(now)
  if (period > today) return fail("period is in the future.")
  if (period < today - (story.backfillDays + LATE_UPLOAD_GRACE_DAYS) * DAY_MS) {
    return fail(`period is older than the story's backfill window plus ${LATE_UPLOAD_GRACE_DAYS} days.`)
  }

  const dimensionKeys = story.dimensions.map((dimension) => dimension.key)
  const measureKeys = story.measures.map((measure) => measure.key)
  const rowKeys = ["dims", ...measureKeys]
  const seen = new Set<string>()
  const rows: SnapshotRow[] = []
  for (const [index, row] of snapshot.rows.entries()) {
    if (!object(row) || !only(row, rowKeys)) return fail(`Row ${index} contains unsupported fields.`)
    if (!has(row, rowKeys)) return fail(`Row ${index} must contain dims and every measure.`)
    const dims = row.dims
    if (!object(dims) || !only(dims, dimensionKeys) || !has(dims, dimensionKeys)) {
      return fail(`Row ${index} dims must name exactly the story's dimensions.`)
    }

    const canonicalDims: Record<string, string> = {}
    for (const dimension of story.dimensions) {
      const value = dims[dimension.key]
      if (typeof value !== "string" || !dimension.values.includes(value)) {
        return fail(`Row ${index} has a value outside the "${dimension.key}" enum.`)
      }
      canonicalDims[dimension.key] = value
    }
    const combination = JSON.stringify(dimensionKeys.map((key) => canonicalDims[key]))
    if (seen.has(combination)) return fail(`Row ${index} repeats a dimension combination.`)
    seen.add(combination)

    const canonical: SnapshotRow = { dims: canonicalDims }
    let total = 0
    for (const measure of story.measures) {
      const value = row[measure.key]
      if (!integer(value, 0, measure.max)) {
        return fail(`Row ${index} measure "${measure.key}" must be an integer from 0 to ${measure.max}.`)
      }
      canonical[measure.key] = value
      total += value
    }
    if (total === 0) return fail(`Row ${index} is all zero; zero rows must be omitted.`)
    rows.push(canonical)
  }

  rows.sort((left, right) => compareDims(left.dims, right.dims, dimensionKeys))
  return { ok: true, value: { ...snapshot, rows } }
}

function compareDims(left: Record<string, string>, right: Record<string, string>, keys: string[]): number {
  for (const key of keys) {
    if (left[key] < right[key]) return -1
    if (left[key] > right[key]) return 1
  }
  return 0
}

/** Sums canonical rows from many subjects into subject-free totals, one row per dimension combination. */
export function sumRows(snapshots: SnapshotRow[][], story: StoryDefinition): SnapshotRow[] {
  const dimensionKeys = story.dimensions.map((dimension) => dimension.key)
  const totals = new Map<string, SnapshotRow>()
  for (const rows of snapshots) {
    for (const row of rows) {
      const key = JSON.stringify(dimensionKeys.map((dimension) => row.dims[dimension]))
      let total = totals.get(key)
      if (!total) {
        total = { dims: { ...row.dims } }
        for (const measure of story.measures) total[measure.key] = 0
        totals.set(key, total)
      }
      for (const measure of story.measures) {
        total[measure.key] = (total[measure.key] as number) + ((row[measure.key] as number | undefined) ?? 0)
      }
    }
  }
  return [...totals.values()].sort((left, right) => compareDims(left.dims, right.dims, dimensionKeys))
}

