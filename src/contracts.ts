function validateModeAndLabel(input: Record<string, unknown>): Result<SubjectUpdate> {
  if (input.mode === "anonymous") {
    if (input.label !== undefined && input.label !== null) return fail("An anonymous subject cannot have a label.")
    return { ok: true, value: { mode: "anonymous", label: null } }
  }
  if (input.mode === "named") {
    const label = text(input.label, 1, 40)
    if (!label || CONTROL.test(label)) return fail("A named subject needs a label of 1 to 40 printable characters.")
    return { ok: true, value: { mode: "named", label } }
  }
  return fail("mode must be \"anonymous\" or \"named\".")
}

export function validateRegistration(input: unknown): Result<SubjectRegistration> {
  if (!object(input) || !only(input, ["subjectId", "secretHash", "mode", "label"])) {
    return fail("The registration contains unsupported fields.")
  }
  if (!isUuid(input.subjectId)) return fail("subjectId must be a UUID.")
  if (typeof input.secretHash !== "string" || !SHA256_HEX.test(input.secretHash)) {
    return fail("secretHash must be a lowercase hex SHA-256.")
  }
  const identity = validateModeAndLabel(input)
  if (!identity.ok) return identity
  return {
    ok: true,
    value: { subjectId: input.subjectId.toLowerCase(), secretHash: input.secretHash, ...identity.value },
  }
}

export function validateSubjectUpdate(input: unknown): Result<SubjectUpdate> {
  if (!object(input) || !only(input, ["mode", "label"])) return fail("The update contains unsupported fields.")
  return validateModeAndLabel(input)
}

export interface SnapshotBatch {
  subjectId: string
  snapshots: unknown[]
}

export function validateBatch(input: unknown): Result<SnapshotBatch> {
  if (!object(input) || !only(input, ["subjectId", "snapshots"]) || !has(input, ["subjectId", "snapshots"])) {
    return fail("The batch must be exactly { subjectId, snapshots }.")
  }
  if (!isUuid(input.subjectId)) return fail("subjectId must be a UUID.")
  if (!Array.isArray(input.snapshots) || input.snapshots.length < 1 || input.snapshots.length > MAX_BATCH_SNAPSHOTS) {
    return fail(`snapshots must contain 1 to ${MAX_BATCH_SNAPSHOTS} items.`)
  }
  return { ok: true, value: { subjectId: input.subjectId.toLowerCase(), snapshots: input.snapshots } }
}
