// Pure validation for Usage Insights payloads. No Workers APIs here: the schema conformance test
// imports this module under Node as well.
//
// Patterns and bounds mirror RedLeaf's UsageContractValidator and the generated
// schemas/usage/v1/*.schema.json. The Worker adds what only it can check: enum membership against
// the stored story, the period window, and generous size caps (MAX_* below) as defence in depth.

export type MeasureType = "count" | "seconds"
export type SubjectMode = "anonymous" | "named"
export type StoryStatus = "active" | "deprecated"
export type ClientObservation = "theme"

export interface StoryDimension {
  key: string
  values: string[]
}

export interface StoryMeasure {
  key: string
  type: MeasureType
  max: number
}

/**
 * Canonical story definition, stored byte-for-byte in `stories.definition_json`. `status` is not
 * part of it: lifecycle belongs to the Worker's `stories.status` column.
 */
export interface StoryDefinition {
  schemaVersion: 1
  storyId: string
  version: number
  question: string
  shares: string
  period: "day"
  backfillDays: number
  dimensions: StoryDimension[]
  measures: StoryMeasure[]
  clientObservations: ClientObservation[]
  introducedIn: string
}

/** A definition as submitted: the schema requires `status`. */
export interface SubmittedStory {
  definition: StoryDefinition
  status: StoryStatus
}

export interface SnapshotRow {
  dims: Record<string, string>
  [measure: string]: number | Record<string, string>
}

export interface Snapshot {
  schemaVersion: 1
  snapshotId: string
  storyId: string
  storyVersion: number
  period: string
  rows: SnapshotRow[]
}

/** The story-independent part of a snapshot, checked before the story definition is looked up. */
export interface SnapshotEnvelope {
  schemaVersion: 1
  snapshotId: string
  storyId: string
  storyVersion: number
  period: string
  rows: unknown[]
}

export interface SubjectRegistration {
  subjectId: string
  secretHash: string
  mode: SubjectMode
  label: string | null
}

export interface SubjectUpdate {
  mode: SubjectMode
  label: string | null
}

export type Result<T> = { ok: true; value: T } | { ok: false; message: string }

export const MAX_BATCH_SNAPSHOTS = 50
export const MAX_BACKFILL_DAYS = 30
export const LATE_UPLOAD_GRACE_DAYS = 7
export const MAX_IDENTIFIER_LENGTH = 64
export const MAX_MEASURE_VALUE = Number.MAX_SAFE_INTEGER
// Worker-only caps; the schema leaves these open.
export const MAX_DIMENSIONS = 16
export const MAX_DIMENSION_VALUES = 256
export const MAX_MEASURES = 32
export const MAX_ROWS = 2000
export const MAX_STORY_VERSION = 10_000

const CLIENT_OBSERVATIONS: readonly string[] = ["theme"]
const STORY_ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/
const KEY = /^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$/
const MEMBER = /^[a-z0-9]+(?:-[a-z0-9]+)*$/
const SEMVER = /^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/
const SNAPSHOT_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/
const NON_BLANK = /\S/
// Subject ids are generated by the kernel; accept either case and store lowercase.
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
const SHA256_HEX = /^[0-9a-f]{64}$/
const DATE = /^(\d{4})-(\d{2})-(\d{2})$/
// Control characters and line/paragraph separators are refused in subject labels.
const CONTROL = new RegExp("[\\u0000-\\u001f\\u007f-\\u009f\\u2028\\u2029]")

const DAY_MS = 86_400_000

function fail<T>(message: string): Result<T> {
  return { ok: false, message }
}

function object(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
}

function only(value: Record<string, unknown>, keys: readonly string[]): boolean {
  const allowed = new Set(keys)
  return Object.keys(value).every((key) => allowed.has(key))
}

function has(value: Record<string, unknown>, keys: readonly string[]): boolean {
  return keys.every((key) => Object.hasOwn(value, key))
}

function integer(value: unknown, min: number, max: number): value is number {
  return typeof value === "number" && Number.isSafeInteger(value) && value >= min && value <= max
}

function text(value: unknown, min: number, max: number): string | null {
  if (typeof value !== "string") return null
  const normalized = value.trim()
  return normalized.length >= min && normalized.length <= max ? normalized : null
}

function identifier(pattern: RegExp, value: unknown): value is string {
  return typeof value === "string" && value.length <= MAX_IDENTIFIER_LENGTH && pattern.test(value)
}

export function isStoryId(value: unknown): value is string {
  return identifier(STORY_ID, value)
}

export function isUuid(value: unknown): value is string {
  return typeof value === "string" && UUID.test(value)
}

/** Parses a `YYYY-MM-DD` string that names a real calendar day and returns its UTC midnight. */
export function parseUtcDay(value: unknown): number | null {
  if (typeof value !== "string") return null
  const match = DATE.exec(value)
  if (!match) return null
  const [year, month, day] = [Number(match[1]), Number(match[2]), Number(match[3])]
  const time = Date.UTC(year, month - 1, day)
  const date = new Date(time)
  if (date.getUTCFullYear() !== year || date.getUTCMonth() !== month - 1 || date.getUTCDate() !== day) return null
  return time
}

export function utcDay(now: Date): number {
  return Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate())
}

export function formatUtcDay(time: number): string {
  return new Date(time).toISOString().slice(0, 10)
}

// ---------------------------------------------------------------------------------------------
// Story definitions
// ---------------------------------------------------------------------------------------------

const STORY_KEYS = [
  "schemaVersion", "storyId", "version", "status", "question", "shares", "period", "backfillDays",
  "dimensions", "measures", "clientObservations", "introducedIn",
] as const

/** Validates a story definition as generated by RedLeaf (usage-story.schema.json). */
export function validateStoryDefinition(input: unknown): Result<SubmittedStory> {
  if (!object(input) || !only(input, STORY_KEYS)) return fail("The story definition contains unsupported fields.")
  if (!has(input, STORY_KEYS)) return fail("The story definition is missing required fields.")
  if (input.schemaVersion !== 1) return fail("Unsupported story schema version.")
  if (!isStoryId(input.storyId)) return fail("storyId must be a kebab-case id of at most 64 characters.")
  if (!integer(input.version, 1, MAX_STORY_VERSION)) return fail("version must be a positive integer.")
  if (input.status !== "active" && input.status !== "deprecated") return fail("status must be \"active\" or \"deprecated\".")
  if (typeof input.question !== "string" || !NON_BLANK.test(input.question)
    || typeof input.shares !== "string" || !NON_BLANK.test(input.shares)) {
    return fail("question and shares must be non-empty text.")
  }
  if (input.period !== "day") return fail("period must be \"day\".")
  if (!integer(input.backfillDays, 0, MAX_BACKFILL_DAYS)) return fail(`backfillDays must be an integer from 0 to ${MAX_BACKFILL_DAYS}.`)
  if (typeof input.introducedIn !== "string" || !SEMVER.test(input.introducedIn)) {
    return fail("introducedIn must be a release version.")
  }

  if (!Array.isArray(input.dimensions) || input.dimensions.length > MAX_DIMENSIONS) {
    return fail(`dimensions must be an array of at most ${MAX_DIMENSIONS} entries.`)
  }
  const dimensions: StoryDimension[] = []
  const keys = new Set<string>()
  for (const dimension of input.dimensions) {
    if (!object(dimension) || !only(dimension, ["key", "values"]) || !has(dimension, ["key", "values"])) {
      return fail("Each dimension must be exactly { key, values }.")
    }
    if (!identifier(KEY, dimension.key)) return fail("Dimension keys must be snake_case.")
    if (keys.has(dimension.key)) return fail(`Key "${dimension.key}" is declared twice.`)
    keys.add(dimension.key)
    const values = dimension.values
    if (!Array.isArray(values) || values.length < 1 || values.length > MAX_DIMENSION_VALUES) {
      return fail(`Dimension "${dimension.key}" must list 1 to ${MAX_DIMENSION_VALUES} values.`)
    }
    if (!values.every((value) => identifier(MEMBER, value))) {
      return fail(`Dimension "${dimension.key}" values must be kebab-case.`)
    }
    if (new Set(values).size !== values.length) return fail(`Dimension "${dimension.key}" lists a value twice.`)
    dimensions.push({ key: dimension.key, values: [...values] as string[] })
  }

  if (!Array.isArray(input.measures) || input.measures.length < 1 || input.measures.length > MAX_MEASURES) {
    return fail(`measures must list 1 to ${MAX_MEASURES} entries.`)
  }
  const measures: StoryMeasure[] = []
  for (const measure of input.measures) {
    if (!object(measure) || !only(measure, ["key", "type", "max"]) || !has(measure, ["key", "type", "max"])) {
      return fail("Each measure must be exactly { key, type, max }.")
    }
    if (!identifier(KEY, measure.key) || measure.key === "dims") {
      return fail("Measure keys must be snake_case; \"dims\" is reserved.")
    }
    if (keys.has(measure.key)) return fail(`Key "${measure.key}" is declared twice.`)
    keys.add(measure.key)
    if (measure.type !== "count" && measure.type !== "seconds") return fail("Measure type must be \"count\" or \"seconds\".")
    if (!integer(measure.max, 1, MAX_MEASURE_VALUE)) return fail("Measure max must be a positive integer.")
    measures.push({ key: measure.key, type: measure.type, max: measure.max })
  }

  const observations = input.clientObservations
  if (!Array.isArray(observations)
    || !observations.every((value) => typeof value === "string" && CLIENT_OBSERVATIONS.includes(value))
    || new Set(observations).size !== observations.length) {
    return fail("clientObservations must be unique known observations.")
  }

  return {
    ok: true,
    value: {
      status: input.status,
      definition: {
        schemaVersion: 1,
        storyId: input.storyId,
        version: input.version,
        question: input.question,
        shares: input.shares,
        period: "day",
        backfillDays: input.backfillDays,
        dimensions,
        measures,
        clientObservations: [...observations] as ClientObservation[],
        introducedIn: input.introducedIn,
      },
    },
  }
}

/** Fixed key order, so equal definitions always serialize to the same bytes. */
export function canonicalStoryJson(definition: StoryDefinition): string {
  return JSON.stringify({
    schemaVersion: definition.schemaVersion,
    storyId: definition.storyId,
    version: definition.version,
    question: definition.question,
    shares: definition.shares,
    period: definition.period,
    backfillDays: definition.backfillDays,
    dimensions: definition.dimensions.map((dimension) => ({ key: dimension.key, values: dimension.values })),
    measures: definition.measures.map((measure) => ({ key: measure.key, type: measure.type, max: measure.max })),
    clientObservations: definition.clientObservations,
    introducedIn: definition.introducedIn,
  })
}

/** The definition as the schema describes it, with the Worker's current lifecycle status. */
export function publishedStory(definition: StoryDefinition, status: StoryStatus) {
  const { schemaVersion, storyId, version, ...rest } = definition
  return { schemaVersion, storyId, version, status, ...rest }
}

